"""Generate a bounded integer sRGB lookup; no floating point in the kernel."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]

def main():
    values = []
    for channel in range(256):
        encoded = channel/255
        linear = encoded/12.92 if encoded <= .04045 else ((encoded+.055)/1.055)**2.4
        values.append(round(linear*65535))
    text = '/* Generated by tools/design/components12.py: linear sRGB, unsigned Q16. */\n'
    text += '#ifndef ENGACER_LUMINANCE12_H\n#define ENGACER_LUMINANCE12_H\n'
    text += 'static const uint16_t ui12_linear[256]={\n'
    text += ''.join(' '+','.join(map(str,values[n:n+16]))+',\n' for n in range(0,256,16))
    text += '};\n#endif\n'
    (ROOT/'include/engine/ui/luminance12.h').write_bytes(text.encode())

if __name__ == '__main__':
    main()
